from __future__ import annotations
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backend.demo_data import SAMPLES, public_samples
from backend.engine import run_check
from backend.serp import DemoSerpClient

def build_reports():
    reports = {}
    for s in SAMPLES:
        reports[s["id"]] = run_check(s["mode"], s["inputs"], DemoSerpClient(s["responses"]), source="demo", sample_id=s["id"])
    return reports

def safe_script(text):
    return text.replace("</script", "<\\/script")

def main():
    payload = {"samples": public_samples(), "reports": build_reports()}
    data_js = "/* generated by scripts/build_static_demo.py, do not edit */\nwindow.TRUSTLENS_DEMO = " + json.dumps(payload, ensure_ascii=False) + ";\n"
    (ROOT / "frontend/js/demo_reports.js").write_text(data_js, encoding="utf-8")
    page = (ROOT / "frontend/index.html").read_text(encoding="utf-8")
    css = (ROOT / "frontend/css/styles.css").read_text(encoding="utf-8")
    app = (ROOT / "frontend/js/app.js").read_text(encoding="utf-8")
    page = page.replace('<link rel="stylesheet" href="css/styles.css">', f"<style>\n{css}\n</style>")
    page = page.replace('<script src="js/demo_reports.js"></script>', f"<script>\n{safe_script(data_js)}</script>")
    page = page.replace('<script src="js/app.js"></script>', f"<script>\n{safe_script(app)}</script>")
    out = ROOT / "dist"; out.mkdir(exist_ok=True)
    (out / "trustlens-demo.html").write_text(page, encoding="utf-8")
    print(f"Wrote frontend/js/demo_reports.js ({len(payload['reports'])} reports)")
    print(f"Wrote dist/trustlens-demo.html ({len(page) // 1024} KB)")

if __name__ == "__main__":
    main()
